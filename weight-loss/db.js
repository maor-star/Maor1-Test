if (db.prepare("SELECT COUNT(*) AS n FROM tips WHERE kind = 'rule'").get().n === 0) {
  const insertTip = db.prepare("INSERT INTO tips (text, position, kind) VALUES (?, ?, 'rule')");
  db.transaction((rows) => rows.forEach((text, i) => insertTip.run(text, i)))(TIP_SEED);
}

// Seeded by text rather than by an empty-table check, so an existing database picks
// up the slogans on the next boot without duplicating what the editor already added.
const hasSlogan = db.prepare("SELECT 1 FROM tips WHERE kind = 'slogan' AND text = ?");
const insertSlogan = db.prepare("INSERT INTO tips (text, position, kind) VALUES (?, ?, 'slogan')");
db.transaction((rows) => rows.forEach((text, i) => {
  if (!hasSlogan.get(text)) insertSlogan.run(text, i);
}))(SLOGAN_SEED);

const upsertPost = db.prepare(`
  INSERT INTO posts (slug, title, category, excerpt, content, read_minutes)
  VALUES (@slug, @title, @category, @excerpt, @content, @read_minutes)
  ON CONFLICT (slug) DO UPDATE SET
    title = excluded.title,
    category = excluded.category,
    excerpt = excluded.excerpt,
    content = excluded.content,
    read_minutes = excluded.read_minutes
`);
db.transaction((rows) => rows.forEach((r) => upsertPost.run(r)))(POST_SEED);

